#!/usr/bin/env bash
# run.sh — Validate prepared audit runtime, load config, and run OMP.
# Usage: ./run.sh "audit the target repo"
#        ./run.sh                   (opens OMP interactive)
#        ./run.sh --fresh "audit a new target" (ignore prior audit selection)
#        ./run.sh login [provider]   (native OMP login; no audit readiness required)
# --fresh is consumed here; arguments after a literal -- are passed unchanged.
set -euo pipefail

HARNESS_ROOT="$(cd "$(dirname "$0")" && pwd)"
audit_fresh=0
omp_args=()
parse_options=1
for argument in "$@"; do
    if [ "$parse_options" -eq 1 ]; then
        case "$argument" in
            --) parse_options=0 ;;
            --fresh) audit_fresh=1; continue ;;
            --advantage)
                echo "[error] For terminal Advantage startup use ./advantage.sh <completed-audit-base> or ./run_local.sh --advantage <completed-audit-base>; inside OMP request Advantage in the current session." >&2
                exit 2 ;;
        esac
    fi
    omp_args+=("$argument")
done
# Preserve an empty interactive invocation under macOS Bash's nounset behavior.
set -- ${omp_args[@]+"${omp_args[@]}"}
# Use the same bundled executable that toolchain readiness validates.
OMP_BIN="${HARNESS_ROOT}/bins/omp"
if [ ! -x "${OMP_BIN}" ]; then
    echo "[error] bundled OMP is missing or not executable — run: bash scripts/install-tools.sh" >&2
    exit 1
fi
export PI_NATIVES_DIR="${HARNESS_ROOT}/bins"

# Diagnostics must work before configuration, credentials, or scanners are ready.
case "${1:-}" in
    --help|-h)
        printf '%s\n' \
            'VulnOps: ./run.sh [--fresh] [OMP arguments]' \
            'Login:   ./run.sh login [provider] (harness-local OMP credentials)' \
            'Arguments after -- are passed unchanged.' ''
        exec "$OMP_BIN" "$@" ;;
    --version|-v) exec "$OMP_BIN" "$@" ;;
esac


# Keep tool homes, caches, temp files, and agent side effects inside the
# harness repo during audit execution.
# shellcheck source=scripts/harness-lib.sh
source "${HARNESS_ROOT}/scripts/harness-lib.sh"
harness_setup_containment "$HARNESS_ROOT"

# Login and audit startup share OMP's persistent credential store. OMP owns
# provider selection, OAuth refresh, and credential storage; no token extraction.
if [ "${1:-}" = "login" ]; then
    cd "$HARNESS_ROOT"
    exec "$OMP_BIN" "$@"
fi

# Drop stale agent context from previous harness runs before OMP starts.
rm -f "${HARNESS_ROOT}/.harness/agent-context.json"

# Load config.toml env vars. OMP state itself is generated by bootstrap-omp.sh;
# parse-config.py stays read-only so validation cannot mutate runtime config.
config_exports="$("${HARNESS_ROOT}/scripts/load-config.sh")" || exit 1
eval "$config_exports"
# This request belongs only to this launch, never to an inherited environment.
export VULNOPS_AUDIT_FRESH="$audit_fresh"


# Seed harness-local OMP config/model registry so OMP starts without the setup
# wizard and without touching the operator's real home directory.
harness_loading 2 "configuration" "${HARNESS_ROOT}/scripts/bootstrap-omp.sh" >/dev/null

# Audit runtime must be fully prepared before OMP starts. Bootstrap commands
# such as install-tools.sh, fetch-osv-db.sh, dependency setup, and clone-target.sh
# stay outside this path.
harness_loading 3 "toolchain checks" "${HARNESS_ROOT}/scripts/validate-config.sh" >/dev/null

# Tag audit context initialized or resumed by this launcher so shutdown can
# fail-close only work owned by this OMP session.
AUDIT_CONTEXT_PATH="${VULNOPS_AUDIT_CONTEXT:-${HARNESS_ROOT}/.harness/audit-context.json}"
export VULNOPS_OMP_CONTROLLER_SELECTOR="$OMP_MODEL_SELECTOR"
VULNOPS_LAUNCHER_SESSION_ID="$(date -u +%Y%m%dT%H%M%SZ)-$$-${RANDOM}${RANDOM}"
VULNOPS_LAUNCHER_PID=$$
export VULNOPS_LAUNCHER_SESSION_ID VULNOPS_LAUNCHER_PID
unset VULNOPS_OMP_RUNTIME_CONFIG VULNOPS_ADVANTAGE_LAUNCHER_SESSION_ID VULNOPS_ADVANTAGE_LAUNCH_REQUEST VULNOPS_ADVANTAGE_CONTEXT VULNOPS_ADVANTAGE_CALL

close_interrupted_audit() {
    if ! python3 "${HARNESS_ROOT}/scripts/close-interrupted-run.py" \
        "$AUDIT_CONTEXT_PATH" --launcher-session-id "$VULNOPS_LAUNCHER_SESSION_ID"; then
        echo "[warning] could not close interrupted audit state; the next initialization will recover it" >&2
        return 1
    fi
}
finish_launcher() {
    local status="${1:-$?}"
    trap - EXIT INT TERM
    close_interrupted_audit || { if [ "$status" -eq 0 ]; then status=1; fi; }
    rm -f "${VULNOPS_OMP_RUNTIME_CONFIG:-}"
    exit "$status"
}
trap 'finish_launcher $?' EXIT
trap 'finish_launcher 130' INT
trap 'finish_launcher 143' TERM
harness_prepare_omp_runtime "$HARNESS_ROOT"

# The shared allowlist also drives the live lifecycle readiness probe.
cd "$HARNESS_ROOT"
audit_status=0
"${OMP_BIN}" \
    --append-system-prompt "${HARNESS_ROOT}/.omp/main/vulnops-main.md" \
    --tools "$(harness_omp_tools)" \
    --config "$VULNOPS_OMP_RUNTIME_CONFIG" \
    --extension "${HARNESS_ROOT}/.omp/guards/target-readonly.ts" \
    --approval-mode yolo \
    "$@" \
    --model "${OMP_MODEL_SELECTOR%:*}" \
    --thinking "${OMP_MODEL_SELECTOR##*:}" || audit_status=$?

exit "$audit_status"
